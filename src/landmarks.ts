/** town name → 10 level names (real landmarks padded with flavors) */
export function landmarksFor(town: string): string[] {
  const real = REAL[town] ?? [];
  const upper = town.toUpperCase();
  const generic = [
    `${upper} MARKET`,
    `${upper} JUNCTION`,
    `${upper} ROUNDABOUT`,
    `OLD ${upper} ROAD`,
    `${upper} MOTOR PARK`,
    `UPPER ${upper}`,
    `${upper} CENTRAL`,
    `${upper} WATERSIDE`,
    `${upper} SQUARE`,
    `NEW ${upper} LAYOUT`,
  ];
  const out: string[] = [];
  for (const name of [...real, ...generic]) {
    if (out.length >= 10) break;
    if (!out.includes(name)) out.push(name);
  }
  return out;
}

/** level name for index n (1..500) — milestone town + slot in the ten-pack */
export function levelName(n: number): string {
  const idx = Math.floor((n - 1) / 10);
  const town = MILESTONE_TOWNS[Math.min(idx, MILESTONE_TOWNS.length - 1)];
  return landmarksFor(town)[(n - 1) % 10];
}
